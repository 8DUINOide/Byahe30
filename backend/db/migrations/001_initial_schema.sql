-- Byahe30 base schema for PostgreSQL / Supabase with PostGIS.
create extension if not exists postgis;

create table if not exists corridors (
    id text primary key,
    name text not null,
    region text not null,
    timezone text not null default 'Asia/Manila',
    is_active boolean not null default true,
    created_at timestamptz not null default now()
);

create table if not exists routes (
    route_id text primary key,
    corridor_id text not null references corridors(id) on delete cascade,
    route_short_name text not null,
    route_long_name text not null,
    mode text not null,
    stop_ids jsonb not null,
    unique (corridor_id, route_id)
);

create table if not exists stops (
    stop_id text primary key,
    corridor_id text not null references corridors(id) on delete cascade,
    name text not null,
    sequence_order integer not null check (sequence_order > 0),
    lat double precision not null check (lat between -90 and 90),
    lng double precision not null check (lng between -180 and 180),
    location geography(point, 4326) generated always as
        (st_setsrid(st_makepoint(lng, lat), 4326)::geography) stored,
    is_transfer_hub boolean not null default false,
    direction text not null default 'northbound' check (direction in ('northbound', 'southbound')),
    landmarks jsonb not null default '[]'::jsonb,
    unique (corridor_id, sequence_order),
    unique (corridor_id, stop_id)
);

create index if not exists stops_location_gix on stops using gist (location);

create table if not exists segments (
    segment_id text primary key,
    corridor_id text not null references corridors(id) on delete cascade,
    from_stop_id text not null,
    to_stop_id text not null,
    distance_km double precision not null check (distance_km > 0),
    baseline_duration_sec integer not null check (baseline_duration_sec > 0),
    polyline_geojson jsonb,
    route_geometry geometry(linestring, 4326),
    unique (corridor_id, from_stop_id, to_stop_id),
    foreign key (corridor_id, from_stop_id) references stops(corridor_id, stop_id),
    foreign key (corridor_id, to_stop_id) references stops(corridor_id, stop_id),
    check (from_stop_id <> to_stop_id)
);

create index if not exists segments_geometry_gix on segments using gist (route_geometry);

create table if not exists headway_schedules (
    schedule_id text primary key,
    corridor_id text not null references corridors(id) on delete cascade,
    vehicle_type text not null check (vehicle_type in ('van', 'jeepney', 'bus', 'any')),
    start_time time not null,
    end_time time not null,
    headway_minutes integer not null check (headway_minutes > 0),
    day_type text not null check (day_type in ('weekday', 'weekend', 'daily')),
    check (start_time < end_time)
);

create table if not exists telemetry_logs (
    id bigint generated by default as identity primary key,
    segment_id text not null references segments(segment_id) on delete cascade,
    recorded_at timestamptz not null,
    live_duration_sec integer not null check (live_duration_sec > 0),
    congestion_ratio double precision not null check (congestion_ratio >= 0),
    source text not null check (source in ('live_routing', 'historical_baseline', 'seeded_baseline'))
);

create index if not exists telemetry_segment_recorded_idx
    on telemetry_logs (segment_id, recorded_at desc);

create index if not exists telemetry_recorded_brin_idx
    on telemetry_logs using brin (recorded_at);

alter table stops add column if not exists direction text not null default 'northbound';
alter table stops add column if not exists landmarks jsonb not null default '[]'::jsonb;
alter table stops drop constraint if exists stops_direction_check;
alter table stops add constraint stops_direction_check check (direction in ('northbound', 'southbound'));
alter table telemetry_logs add column if not exists incidents jsonb not null default '[]'::jsonb;
alter table telemetry_logs add column if not exists weather jsonb;

create table if not exists live_vehicle_trips (
    trip_id uuid primary key,
    corridor_id text not null references corridors(id) on delete cascade,
    route_id text not null references routes(route_id) on delete cascade,
    vehicle_type text not null check (vehicle_type in ('van', 'jeepney', 'bus')),
    reporter_type text not null default 'driver' check (reporter_type in ('driver', 'commuter', 'demo')),
    direction text not null check (direction in ('forward', 'reverse')),
    reporter_token_hash char(64) not null,
    started_at timestamptz not null default now(),
    last_seen_at timestamptz not null default now(),
    latitude double precision check (latitude is null or latitude between -90 and 90),
    longitude double precision check (longitude is null or longitude between -180 and 180),
    accuracy_m double precision check (accuracy_m is null or accuracy_m >= 0),
    progress_km double precision check (progress_km is null or progress_km >= 0),
    previous_progress_km double precision,
    previous_position_at timestamptz,
    observed_speed_mps double precision check (observed_speed_mps is null or observed_speed_mps between 0 and 40),
    ended_at timestamptz
);

alter table live_vehicle_trips
    add column if not exists reporter_type text not null default 'driver';

alter table live_vehicle_trips
    drop constraint if exists live_vehicle_trips_reporter_type_check;

alter table live_vehicle_trips
    add constraint live_vehicle_trips_reporter_type_check
    check (reporter_type in ('driver', 'commuter', 'demo'));

create index if not exists live_vehicle_corridor_seen_idx
    on live_vehicle_trips (corridor_id, last_seen_at desc)
    where ended_at is null;
